/**
 * Simple schematic 3D models, one per catalog category, built from primitives.
 * These are original illustrations (not MegaZip artwork): each clickable piece
 * stands for one diagram of the category, referenced by its index in
 * CATEGORIES[n].diagrams. Pieces with d = -1 are non-clickable context
 * (e.g. a ghosted car body).
 *
 * Axes: x = car length (front at -x), y = up, z = car width. Units are arbitrary.
 */

/** Stable colour per diagram, shared by the 3D model and the diagram list. */
export const diagramColor = (index: number) => `hsl(${(index * 47 + 205) % 360}, 60%, 52%)`;

export type Vec3 = [number, number, number];
export type Axis = "x" | "y" | "z";

export type Piece = {
  /** Diagram index within the category, or -1 for context. */
  d: number;
  p: Vec3;
  /** Extra rotation (radians), applied on top of the axis orientation. */
  r?: Vec3;
} & (
  | { shape: "box"; size: Vec3 }
  | { shape: "cyl"; radius: number; length: number; axis: Axis }
  | { shape: "sphere"; radius: number }
  | { shape: "torus"; radius: number; tube: number; axis: Axis }
);

const box = (d: number, p: Vec3, size: Vec3, r?: Vec3): Piece => ({ d, shape: "box", p, size, r });
const cyl = (d: number, p: Vec3, radius: number, length: number, axis: Axis = "y"): Piece => ({
  d,
  shape: "cyl",
  p,
  radius,
  length,
  axis,
});
const sph = (d: number, p: Vec3, radius: number): Piece => ({ d, shape: "sphere", p, radius });
const tor = (d: number, p: Vec3, radius: number, tube: number, axis: Axis = "x"): Piece => ({
  d,
  shape: "torus",
  p,
  radius,
  tube,
  axis,
});

